"""Import PostgreSQL node printer labels and field order from a completed PG19 build."""
import argparse
import hashlib
from pathlib import Path
import re

CRATES = Path(__file__).resolve().parents[2] / "crates"
CALL = re.compile(r'WRITE_(\w+)_FIELD\(([\w.]+)(?:, \w+)?\);')


def declarations():
    source = (CRATES / "pgsql-nodes/src/nodes.in").read_text()
    records = re.findall(r'^        (\w+) \(\d+, "(\w+)"\) \{(.*?)^        \}', source, re.M | re.S)
    return {pg: (rust, {name: (attr, t) for attr, name, t in
            re.findall(r'([\w#]+) \["(\w+)"\]: (.+),', body)}) for rust, pg, body in records}


def functions(source):
    return dict(re.findall(r'^_out(\w+)\(StringInfo str,[^\n]+\n\{(.*?)^\}', source, re.M | re.S))


def emit_fields(text, records, pg, indent):
    lines = []
    for line in text.splitlines():
        if not line.strip():
            continue
        match = CALL.fullmatch(line.strip())
        if match is None:
            raise ValueError(f"unsupported {pg} output: {line}")
        kind, name = match.groups()
        ty = pg
        attrs = ["n"]
        for member in name.split("."):
            attr, ty = records[ty][1][member]
            attrs.append(attr)
        path = ".".join(attrs) + (".0" if kind == "ENUM" else "")
        method = "string_node" if kind == "NODE" and ty == "Option<String>" else "field"
        lines.append(f'{indent}w.{method}(" :{name} ", &{path});')
    return lines


def rte(body, records, pg):
    before, tail = body.split('switch (node->rtekind)')
    cases, after = tail.split('\n\t}', 1)
    out = emit_fields(before, records, pg, "        ")
    out.append("        match n.rtekind {")
    cases = re.sub(r"/\*.*?\*/", "", cases, flags=re.S)
    for key, code in re.findall(r'case (RTE_\w+):(.*?)break;', cases, re.S):
        out.append(f"            RTEKind::{key} => {{")
        out.extend(emit_fields(code, records, pg, "                "))
        out.append("            }")
    out += ['            _ => return Err(TreeError::UnknownEnum("RTEKind", n.rtekind.0)),', '        };']
    return out + emit_fields(after, records, pg, "        ")


def generate(run):
    files = run / "patched/src/backend/nodes"
    generated = functions((files / "outfuncs.funcs.c").read_text())
    switches = (files / "outfuncs.switch.c").read_text()
    manual_c = (run / "patched-source/src/backend/nodes/outfuncs.c").read_text()
    manual = functions(manual_c)
    records = declarations()
    out = ["// Generated by generate-tree-output.py. PostgreSQL license in LICENSE-PostgreSQL.",
           "// outfuncs.c SHA-256: " + hashlib.sha256(manual_c.encode()).hexdigest(),
           "tree_records! { n, w;"]
    for pg, (rust, _) in records.items():
        body = generated.get(pg, manual.get(pg, ""))
        if not body:
            if re.search(rf'\bcase T_{pg}:', switches):
                raise ValueError(f"{pg} has dispatch without a writer")
            out.append(f'    {rust} "" {{}}')
            continue
        label = re.search(r'WRITE_NODE_TYPE\("(\w+)"\);', body)[1]
        out.append(f'    {rust} "{label}" {{')
        body = body.split(f'WRITE_NODE_TYPE("{label}");')[1]
        if pg == "RangeTblEntry":
            out.extend(rte(body, records, pg))
        elif pg == "A_Expr":
            out.append("        w.text(match n.kind {")
            for key, actions in re.findall(r'case (AEXPR_\w+):(.*?)break;', body, re.S):
                if "WRITE_NODE_FIELD(name);" not in actions:
                    raise ValueError(f"changed {key} output")
                marker = re.search(r'appendStringInfoString\(str, "( [A-Z_]+)"\);', actions)
                out.append(f'            AExprKind::{key} => "{marker[1] if marker else ""}",')
            out += ['            _ => return Err(TreeError::UnknownEnum("A_Expr_Kind", n.kind.0)),', '        });',
                    '        w.field(" :name ", &n.name);']
            out.extend(emit_fields(body.split('\n\t}', 1)[1], records, pg, "        "))
        elif pg == "BoolExpr":
            out += ["        w.text(match n.boolop {"]
            for key, op in re.findall(r'case (\w+):\s*opstr = "(\w+)";', body):
                out.append(f'            BoolExprType::{key} => " :boolop {op}",')
            out += ['            _ => " :boolop <>",', '        });']
            out.extend(emit_fields(body[body.index("WRITE_NODE_FIELD(args)"):], records, pg, "        "))
        else:
            out.extend(emit_fields(body, records, pg, "        "))
        out.append("    }")
    return "\n".join(out + ["}", ""])


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("run", type=Path)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    target = CRATES / "pgsql-reference/src/tree/records.in"
    generated = generate(args.run)
    if args.check:
        if target.read_text() != generated:
            raise SystemExit(f"generated tree fields differ from {target}")
    else:
        target.write_text(generated)
