#!/usr/bin/env python3
"""Regenerate native parser tables from a prepared, patched PostgreSQL source tree."""
import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tempfile
import xml.etree.ElementTree as ET

DEFAULT_DEST = Path(__file__).resolve().parents[2] / "crates/pg19-tables"
BISON_VERSION = "3.8.2"
ARRAYS = {
    "yytranslate": "H", "yypact": "i", "yydefact": "H",
    "yypgoto": "i", "yydefgoto": "H", "yytable": "h", "yycheck": "h",
    "yyr1": "H", "yyr2": "B",
}


def gram_report(source, work):
    gram = source / "src/backend/parser/gram.y"
    subprocess.run(["bison", "-Wno-deprecated", "-d", "--xml=gram.xml",
                    "-o", "gram.c", str(gram.resolve())], cwd=work, check=True)
    # Only the grammar section is needed. A full PostgreSQL automaton report
    # is tens of megabytes, and ElementTree retains all visited siblings.
    for event, elem in ET.iterparse(work / "gram.xml", events=("start", "end")):
        if event == "start" and elem.tag == "bison-xml-report":
            if elem.get("version") != BISON_VERSION:
                raise ValueError(f"expected Bison {BISON_VERSION}, got {elem.get('version')}")
        if event == "end" and elem.tag == "grammar":
            return gram.read_bytes(), elem, (work / "gram.c").read_text()
    raise ValueError("missing Bison grammar report")


def c_array(c, name):
    values = re.search(r"^static const \w+ " + name + r"\[\]\s*=\s*\{([^}]+)\};", c, re.M)
    if values is None:
        raise ValueError(f"missing array {name}")
    return [int(n) for n in values[1].split(",")]


def explicit_actions(c):
    switch = c.split("switch (yyn)\n", 1)[1].split("      default: break;", 1)[0]
    cases = re.findall(r"^  case (\d+): /\* ", switch, re.M)
    pattern = (r"^  case (\d+): /\* [^\n]+ \*/\n#line (\d+) \"[^\n]*gram.y\"\n"
               r"(.*?)\n#line \d+ \"gram.c\"\n    break;")
    result = {}
    for case, line, body in re.findall(pattern, switch, re.M | re.S):
        result[int(case)] = (int(line), hashlib.sha256(body.strip().encode()).hexdigest())
    if len(result) != len(cases) or not result:
        raise ValueError("unrecognized Bison rule-action dispatch")
    return result


def inventory(grammar, c, arrays):
    actions = explicit_actions(c)
    lines = c_array(c, "yyrline")
    symbols = {s.attrib["name"]: int(s.attrib["symbol-number"])
               for section in ("terminals/terminal", "nonterminals/nonterminal")
               for s in grammar.findall(section)}
    rows = []
    signatures = set()
    for expected, rule in enumerate(grammar.findall("rules/rule"), 1):
        # Bison's generated C indexes productions one higher than its reports.
        number = int(rule.attrib["number"]) + 1
        lhs = rule.findtext("lhs")
        rhs = [s.text for s in rule.findall("rhs/symbol")]
        if (number != expected or symbols[lhs] != arrays["yyr1"][number]
                or len(rhs) != arrays["yyr2"][number]):
            raise ValueError(f"inconsistent Bison production {number}")
        signature = f"{lhs}: {' '.join(rhs) or '%empty'}"
        if "percent_prec" in rule.attrib:
            signature += " %prec " + rule.attrib["percent_prec"]
        if signature in signatures:
            raise ValueError(f"duplicate production identity {signature}")
        signatures.add(signature)
        line, fingerprint = actions.pop(number, (lines[number], "default"))
        rows.append(f"{signature}\t{line}\t{fingerprint}\n")
    if actions or len(rows) + 1 != len(arrays["yyr1"]):
        raise ValueError("production and action counts disagree")
    return rows, symbols


def generate(source, work):
    gram, grammar, c = gram_report(source, work)
    arrays = {name: c_array(c, name) for name in ARRAYS}
    rows, symbols = inventory(grammar, c, arrays)
    constants = dict(re.findall(r"^#define (YY\w+)\s+\(?(-?\d+)\)?\s*$", c, re.M))
    metadata = ["// Generated by tools/pg19/generate-tables.py.\n"]
    for name in ("YYFINAL", "YYLAST", "YYNTOKENS", "YYNSTATES", "YYPACT_NINF", "YYTABLE_NINF"):
        metadata.append(f"const {name}: i32 = {constants[name]};\n")
    blob = bytearray()
    def write_array(name, fmt, values):
        metadata.append(f"const {name.upper()}: usize = {len(blob)};\n")
        blob.extend(struct.pack(f"<{len(values)}{fmt}", *values))
    for name, fmt in ARRAYS.items():
        write_array(name, fmt, arrays[name])
    def write_offsets(name, lines):
        offsets = [0]
        for line in lines:
            offsets.append(offsets[-1] + len(line.encode()))
        write_array(name, "I", offsets)
    write_offsets("rule_offsets", rows)
    names = [""] * (max(symbols.values()) + 1)
    for name, number in symbols.items():
        names[number] = name
    # Bison excludes its internal undefined-token symbol from the XML list.
    names[2] = "$undefined"
    if any(not name for name in names):
        raise ValueError("incomplete Bison symbol catalog")
    symbol_lines = [f"{name}\n" for name in names]
    write_offsets("symbol_offsets", symbol_lines)
    for name, size in (("TOKEN_COUNT", len(arrays["yytranslate"])),
                       ("RULE_COUNT", len(rows)), ("SYMBOL_COUNT", len(names))):
        metadata.append(f"const {name}: usize = {size};\n")
    metadata.append(f'pub const GRAMMAR_SHA256: &str = "{hashlib.sha256(gram).hexdigest()}";\n')
    return {
        "src/layout.rs": "".join(metadata).encode(),
        "data/tables.bin": bytes(blob),
        "data/productions.tsv": "".join(rows).encode(),
        "data/symbols.txt": "".join(symbol_lines).encode(),
    }


def action_changes(old, new):
    def digests(data):
        return {sig: digest for sig, _, digest in (row.split("\t") for row in data.decode().splitlines())}
    before, after = digests(old), digests(new)
    for sig in sorted(before.keys() - after.keys()):
        print(f"removed production: {sig}")
    for sig in sorted(after.keys() - before.keys()):
        print(f"added production ({after[sig]}): {sig}")
    for sig in sorted(before.keys() & after.keys()):
        if before[sig] != after[sig]:
            print(f"changed action ({before[sig]} -> {after[sig]}): {sig}")


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("source", type=Path, help="patched-source from pg19-reference import")
    cli.add_argument("--write", action="store_true", help="write regenerated artifacts after reporting drift")
    cli.add_argument("--dest", type=Path, default=DEFAULT_DEST, help="output crate directory")
    args = cli.parse_args()
    with tempfile.TemporaryDirectory() as temp:
        files = generate(args.source, Path(temp))
    changed = []
    for name, data in files.items():
        path = args.dest / name
        old = path.read_bytes() if path.exists() else None
        if old == data:
            continue
        changed.append(name)
        if old is not None and name == "data/productions.tsv":
            action_changes(old, data)
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if changed and not args.write:
        cli.exit(1, f"regeneration differs for {', '.join(changed)}\n")


if __name__ == "__main__":
    main()
