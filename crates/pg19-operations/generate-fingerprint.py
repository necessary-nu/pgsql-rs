"""Generate the native visitor using the C fingerprint generator's field layout."""
import argparse
import json
from pathlib import Path
import re
import subprocess

CRATE = Path(__file__).resolve().parent


def field_statement(kind, name, rust, ty):
    key = json.dumps(name)
    value = f"n.{rust}"
    if kind in ("skip", "ignore"):
        return
    if kind == "list":
        return f"w.list_field({key}, &{value}, at);"
    if kind in ("node_ptr", "specific_node_ptr"):
        return f"w.pointer({key}, {value}.as_deref(), at);"
    if kind == "embedded":
        return f"w.embedded({key}, &{value}, at);"
    if kind == "enum":
        return f"w.symbol({key}, {value}.pg_name());"
    if kind == "int" and ty == "i32":
        return f"w.integer({key}, {value});"
    if kind == "int":
        return f"w.integer({key}, {value}.as_pg());" if ty == "Location" else f"w.integer({key}, {value} as i32);"
    if kind in ("long_int", "uint64"):
        return f"w.integer({key}, {value});"
    if kind == "float":
        return f"w.float({key}, {value});"
    if kind == "int_array":
        return f"w.bitmap({key}, &{value});"
    if kind == "bool":
        return f"w.boolean({key}, {value});"
    if kind == "char":
        return f"w.character({key}, {value});"
    if kind == "char_ptr":
        return f"w.string({key}, {value}.as_deref());"
    if kind == "string":
        return f"w.string({key}, {value}.as_deref().filter(|s| !s.is_empty()));"
    if kind == "res_target_name":
        return f"w.target_name({value}.as_deref(), at);"
    if kind == "a_expr_kind":
        return f"w.expression_kind({value});"
    raise ValueError(f"unsupported fingerprint field {name} ({ty}, {kind})")


def generate(schema):
    script = CRATE.parents[1] / "tools/pg19/libpg_query/scripts/generate_fingerprint_outfuncs.rb"
    layout = json.loads(subprocess.check_output(["ruby", script, "--layout"], cwd=schema))
    native = (CRATE.parent / "pg19-nodes/src/nodes.in").read_text()
    lines = ["// Generated by generate-fingerprint.py from the compatibility fingerprint rules.",
             "fingerprint_records! { n, w, at;"]
    for record, pg_name, body in re.findall(r'^        (\w+) \(\d+, "(\w+)"\) \{(.*?)^        \}', native, re.M | re.S):
        fields = {c: (rust, ty) for rust, c, ty in re.findall(r'([\w#]+) \["(\w+)"\]: (.+),', body)}
        actions = layout[pg_name]
        lines.append(f'    {record} "{pg_name}" {{')
        if actions == 'custom':
            if record != 'RangeVar':
                raise ValueError(f"new custom fingerprint for {record}")
            lines.append("        w.relation(n, at);")
        elif actions != 'skip':
            for cname, _, kind in actions:
                if kind in ("skip", "ignore"):
                    continue
                statement = field_statement(kind, cname, *fields[cname])
                lines.append(f"        {statement}")
        lines.append("    }")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("schema", type=Path, help="schema build directory containing srcdata/")
    cli.add_argument("--check", action="store_true")
    options = cli.parse_args()
    out = CRATE / "src/fingerprint/records.in"
    result = generate(options.schema)
    if options.check:
        if out.read_text() != result:
            cli.exit(1, "generated fingerprint visitor differs\n")
    else:
        out.write_text(result)
