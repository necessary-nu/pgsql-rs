use super::{ident, names, relation, required, Error, Plan, Result};
use pg19_nodes::*;

fn keys(nodes: &[Node], last: &'static str, p: &mut Plan<'_>) -> Result<()> {
    if nodes.is_empty() {
        return Ok(());
    }
    p.text(" (");
    p.text(names(nodes, ", ")?);
    p.text(last);
    p.text(")");
    Ok(())
}

fn foreign_action(action: u8, command: &'static str, p: &mut Plan<'_>) -> Result<()> {
    if action == b'a' {
        return Ok(());
    }
    p.text(command);
    p.text(match action {
        b'r' => "RESTRICT",
        b'c' => "CASCADE",
        b'n' => "SET NULL",
        b'd' => "SET DEFAULT",
        _ => return Err(Error::InvalidField("foreign key action")),
    });
    Ok(())
}
fn foreign(s: &Constraint, p: &mut Plan<'_>) -> Result<()> {
    if !s.fk_attrs.is_empty() {
        p.text("FOREIGN KEY");
        foreign_keys(&s.fk_attrs, s.fk_with_period, p)?;
        p.text(" ")
    }
    p.text("REFERENCES ");
    relation(required(&s.pktable, "Constraint.pktable")?, p, false)?;
    foreign_keys(&s.pk_attrs, s.pk_with_period, p)?;
    match s.fk_matchtype {
        b's' => {}
        b'f' => p.text(" MATCH FULL"),
        b'p' => p.text(" MATCH PARTIAL"),
        _ => return Err(Error::InvalidField("Constraint.fk_matchtype")),
    }
    foreign_action(s.fk_upd_action, " ON UPDATE ", p)?;
    foreign_action(s.fk_del_action, " ON DELETE ", p)?;
    keys(&s.fk_del_set_cols, "", p)
}

fn foreign_keys(nodes: &[Node], period: bool, p: &mut Plan<'_>) -> Result<()> {
    if !period {
        return keys(nodes, "", p);
    }
    let (last, first) = nodes
        .split_last()
        .ok_or(Error::InvalidField("PERIOD column"))?;
    let Node::String(name) = last else {
        return Err(Error::InvalidField("PERIOD column"));
    };
    p.text(" (");
    if !first.is_empty() {
        p.text(names(first, ", ")?);
        p.text(", ")
    }
    p.text("PERIOD ");
    p.text(ident(name)?);
    p.text(")");
    Ok(())
}

pub(super) fn constraint<'a>(c: &'a Constraint, domain: bool, p: &mut Plan<'a>) -> Result<()> {
    use ConstrType as C;
    p.mark(c.location);
    if let Some(n) = &c.conname {
        p.text("CONSTRAINT ");
        p.text(ident(n)?);
        p.text(" ")
    }
    match c.contype {
        C::CONSTR_NULL => p.text("NULL"),
        C::CONSTR_NOTNULL => {
            p.text("NOT NULL");
            if !domain && !c.keys.is_empty() {
                p.text(" ");
                p.text(names(&c.keys, ", ")?)
            }
        }
        C::CONSTR_DEFAULT => {
            p.text("DEFAULT ");
            let n = required(&c.raw_expr, "Constraint.raw_expr")?;
            p.wrapped(
                n,
                super::Role::Restricted,
                super::super::operator::restricted(n),
            );
        }
        C::CONSTR_IDENTITY => {
            p.text(match c.generated_when {
                b'a' => "GENERATED ALWAYS AS IDENTITY",
                b'd' => "GENERATED BY DEFAULT AS IDENTITY",
                _ => return Err(Error::InvalidField("Constraint.generated_when")),
            });
            if !c.options.is_empty() {
                p.text(" (");
                super::sequence::options(&c.options, false, p)?;
                p.text(" )");
            }
        }
        C::CONSTR_GENERATED => {
            p.text("GENERATED ALWAYS AS (");
            p.expr(required(&c.raw_expr, "Constraint.raw_expr")?);
            p.text(match c.generated_kind {
                b's' => ") STORED",
                b'v' => ") VIRTUAL",
                _ => return Err(Error::InvalidField("Constraint.generated_kind")),
            })
        }
        C::CONSTR_CHECK => {
            p.text("CHECK (");
            p.expr(required(&c.raw_expr, "Constraint.raw_expr")?);
            p.text(")")
        }
        C::CONSTR_PRIMARY | C::CONSTR_UNIQUE => {
            p.text(if c.contype == C::CONSTR_PRIMARY {
                "PRIMARY KEY"
            } else if c.nulls_not_distinct {
                "UNIQUE NULLS NOT DISTINCT"
            } else {
                "UNIQUE"
            });
            keys(
                &c.keys,
                if c.without_overlaps {
                    " WITHOUT OVERLAPS"
                } else {
                    ""
                },
                p,
            )?;
            if !c.including.is_empty() {
                p.text(" INCLUDE");
                keys(&c.including, "", p)?
            }
            if !c.options.is_empty() {
                return Err(Error::InvalidField("index storage options"));
            }
            if let Some(i) = &c.indexname {
                p.text(" USING INDEX ");
                p.text(ident(i)?)
            }
            if let Some(ts) = &c.indexspace {
                p.text(" USING INDEX TABLESPACE ");
                p.text(ident(ts)?)
            }
        }
        C::CONSTR_FOREIGN => foreign(c, p)?,
        C::CONSTR_ATTR_DEFERRABLE => p.text("DEFERRABLE"),
        C::CONSTR_ATTR_NOT_DEFERRABLE => p.text("NOT DEFERRABLE"),
        C::CONSTR_ATTR_DEFERRED => p.text("INITIALLY DEFERRED"),
        C::CONSTR_ATTR_IMMEDIATE => p.text("INITIALLY IMMEDIATE"),
        C::CONSTR_ATTR_ENFORCED => p.text("ENFORCED"),
        C::CONSTR_ATTR_NOT_ENFORCED => p.text("NOT ENFORCED"),
        _ => return Err(Error::InvalidField("Constraint.contype")),
    }
    if c.deferrable {
        p.text(" DEFERRABLE")
    }
    if c.initdeferred {
        p.text(" INITIALLY DEFERRED")
    }
    if c.is_no_inherit {
        p.text(" NO INHERIT")
    }
    if matches!(c.contype, C::CONSTR_FOREIGN | C::CONSTR_CHECK) && !c.is_enforced {
        p.text(" NOT ENFORCED")
    }
    if c.skip_validation {
        p.text(" NOT VALID")
    }
    Ok(())
}
