"""Import JSON field selection, order and spellings from the PG19 schema build."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def generate(schema_dir):
    declarations = (ROOT.parent / "pg19-nodes/src/nodes.in").read_text()
    fields = {}
    for name, pg_name, body in re.findall(r'^        (\w+) \(\d+, "(\w+)"\) \{(.*?)^        \}', declarations, re.M | re.S):
        fields[name] = (pg_name, {c: (rust, ty) for rust, c, ty in re.findall(r'([\w#]+) \["(\w+)"\]: (.+),', body)})
    include = schema_dir / "src/include"
    definitions = (include / "pg_query_outfuncs_defs.c").read_text()
    writers = dict(re.findall(r'^_out(\w+)\(OUT_TYPE[^\n]+\n\{(.*?)^\}', definitions, re.M | re.S))
    lines = ["// Generated by generate-json.py using the libpg_query PG19 field writers.", "json_records! { n, out;"]
    for name, (pg_name, rust_fields) in fields.items():
        lines.append(f'    {name} "{pg_name}" {{')
        for line in writers[name].splitlines():
            if not line.strip():
                continue
            call = re.fullmatch(r"  WRITE_(\w+)_FIELD\(([\w, ]+)\);", line)
            if not call:
                raise ValueError(f"unknown {pg_name} JSON writer: {line}")
            kind, args = call[1].lower(), call[2].split(", ")
            json_key, source = args[-2:]
            rust_name, ty = rust_fields[source]
            if kind in ("int", "uint", "uint64", "long"):
                kind = "location" if ty == "Location" else "number"
            if kind in ("node_ptr", "specific_node_ptr"):
                kind = "pointer"
            if call[1] == "SPECIFIC_NODE_PTR" and args[1] == "String":
                kind = "string_node"
            fallible = '?' if kind in {'pointer', 'specific_node', 'float', 'list', 'bitmapset', 'string_node'} else ''
            value = f"n.{rust_name}.pg_name()" if kind == "enum" else f"&n.{rust_name}"
            lines.append(f'        out.write_{kind}("{json_key}", {value}){fallible};')
        lines.append("    }")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema_dir", type=Path, help="directory containing generated src/include and protobuf")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/json-records.in"
    generated = generate(args.schema_dir)
    if args.check:
        if output.read_text() != generated:
            raise SystemExit(f"regenerated JSON mappings differ from {output}")
    else:
        output.write_text(generated)
