use super::{names, relation, required, table, Error, Plan, Result};
use pgsql_nodes::*;

pub(super) fn options<'a>(items: &'a [Node], alter_identity: bool, p: &mut Plan<'a>) -> Result<()> {
    for (i, n) in items.iter().enumerate() {
        if i > 0 {
            p.text(" ")
        }
        let Node::DefElem(d) = n else {
            return Err(Error::InvalidField("sequence option"));
        };
        p.mark(d.location);
        let name = d
            .defname
            .as_deref()
            .ok_or(Error::InvalidField("DefElem.defname"))?;
        if alter_identity && name != "restart" {
            p.text("SET ")
        }
        match (name, d.arg.as_deref()) {
            ("as", Some(Node::TypeName(t))) => {
                p.text("AS ");
                p.typename(t)
            }
            ("cycle", Some(Node::Boolean(c))) => p.text(if *c { "CYCLE" } else { "NO CYCLE" }),
            ("owned_by" | "sequence_name", Some(Node::List(l))) => {
                p.text(if name == "owned_by" {
                    "OWNED BY "
                } else {
                    "SEQUENCE NAME "
                });
                p.text(names(l, ".")?)
            }
            ("minvalue" | "maxvalue", None) => {
                p.text("NO ");
                p.text(name.to_ascii_uppercase())
            }
            ("restart", None) => p.text("RESTART"),
            ("generated", Some(Node::Integer(v))) if alter_identity => p.text(match *v {
                97 => "GENERATED ALWAYS",
                100 => "GENERATED BY DEFAULT",
                _ => return Err(Error::InvalidField("identity generation mode")),
            }),
            ("start" | "cache" | "increment" | "maxvalue" | "minvalue" | "restart", Some(v)) => {
                p.text(name.to_ascii_uppercase());
                p.text(" ");
                match v {
                    Node::Integer(i) => p.text(i.to_string()),
                    Node::Float(f) => p.text(super::super::numeric(f)?),
                    _ => return Err(Error::InvalidField("sequence numeric option")),
                }
            }
            _ => return Err(Error::InvalidField("sequence option")),
        }
    }
    Ok(())
}
pub(super) fn create<'a>(s: &'a CreateSeqStmt, p: &mut Plan<'a>) -> Result<()> {
    let r = required(&s.sequence, "CreateSeqStmt.sequence")?;
    p.text("CREATE ");
    table::persistence(r, p)?;
    p.text("SEQUENCE ");
    if s.if_not_exists {
        p.text("IF NOT EXISTS ")
    }
    relation(r, p, false)?;
    if !s.options.is_empty() {
        p.text(" ");
        options(&s.options, false, p)?
    }
    Ok(())
}
pub(super) fn alter<'a>(s: &'a AlterSeqStmt, p: &mut Plan<'a>) -> Result<()> {
    p.text("ALTER SEQUENCE ");
    if s.missing_ok {
        p.text("IF EXISTS ")
    }
    relation(required(&s.sequence, "AlterSeqStmt.sequence")?, p, false)?;
    if !s.options.is_empty() {
        p.text(" ");
        options(&s.options, false, p)?
    }
    Ok(())
}
